/**
 * @file test_any.cpp
 * @brief Tests LogicOps::any against fixed expected values.
 * @author Mustafa Garip
 */

#include <gtest/gtest.h>
#include <vector>
#include <SushiBLAS/SushiBLAS.hpp>
#include <SushiBLAS/engine_fixture/sushiblas_test.hpp>
#include <SushiBLAS/tensor_expectations/tensor_comparison.hpp>
#include <SushiBLAS/tensor_expectations/tensor_fill.hpp>
using namespace SushiBLAS::Test;

class Medium_AnyTest : public SushiBLASTest {};

TEST_F(Medium_AnyTest, FloatForward) 
{
    auto t = engine->create_tensor({4});
    fill_tensor(t, {1.0f, 0.0f, 3.0f, 0.0f});
    auto out = engine->create_tensor({1});
    SushiBLAS::LogicOps(recorder()).any(t, out);
    recording->run().value();
    
    verify_tensor(out, {1.0f});
}
