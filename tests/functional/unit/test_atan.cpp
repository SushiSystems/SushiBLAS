/**
 * @file test_atan.cpp
 * @brief Tests elementwise().atan against fixed expected values.
 * @author Mustafa Garip
 */

#include <gtest/gtest.h>
#include <vector>
#include <SushiBLAS/SushiBLAS.h>
#include "../../common/test_utils.hpp"

using namespace SushiBLAS::Test;

class Unit_AtanTest : public SushiBLASTest {};

TEST_F(Unit_AtanTest, FloatForward) 
{
    auto t = engine->create_tensor({4});
    fill_tensor(t, {1.0f, 2.0f, -3.0f, 0.5f});
    
    engine->elementwise().atan(t);
    engine->execute().wait();
    
    verify_tensor(t, {0.78540f, 1.10715f, -1.24905f, 0.46365f});
}
